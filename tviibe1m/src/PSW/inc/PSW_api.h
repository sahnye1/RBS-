/**
 * @file    PSW_api.h
 * @brief   PSW 底层库对外 API 声明
 *
 * @note    本文件仅声明 PSW 库对外暴露的函数和类型。
 *          各驱动模块内部接口请参见各自的 .h 文件。
 */

#ifndef __APP_DRV_API_H__
#define __APP_DRV_API_H__

#include <stdbool.h>
#include <stdint.h>

/* ========================================================================================= */
/* PSW 库对内 API                                                                             */
/* ========================================================================================= */
/* ========================================================================== */
/*  开发板初始化                                                               */
/* ========================================================================== */

/**
 * @brief 板级初始化 (SystemInit + 所有模块 Init)
 * @note  CAN 初始化已包含在内部 (board_init 内调用 can_init),
 *        调用前需先用 can_info_cfg 配置 ID、can0_bitrate_set 设置波特率。
 */
void board_init(void);

/* ========================================================================== */
/*  主循环处理                                                                 */
/* ========================================================================== */

/** @brief 10ms 节拍标志 (timer10ms ISR 置位, 主循环消费后清除)
 *  @note  主循环约定: if (g_b10msTick) { PSW_10ms_deal(); } */
extern volatile bool g_b10msTick;

/**
 * @brief 10ms 周期主处理函数
 * @note  喂狗 + 阀诊断 + 轮速 + ADC + 压力 + RTE 数据填充
 */
void PSW_10ms_deal(void);

/* ========================================================================== */
/*  任务计时                                                                   */
/* ========================================================================== */

/** @brief 记录任务起始时刻 (DWT CYCCNT 快照) */
void rcrd_task_start(void);

/** @brief 计算当前任务耗时, 写入 RTETaskTime (单位: 0.1ms) */
void calc_task_time(void);

/* ========================================================================== */
/*  10ms 定时器                                                                */
/* ========================================================================== */

/** @brief 获取 10ms 定时器超时计数
 *  @return 0=未超时, 非0=ISR 触发累计次数 */
uint8_t timer_get_count(void);

/** @brief 清零 10ms 定时器计数 */
void timer_count_dev1(void);


/* ========================================================================================= */
/* PSW 库对外 API                                                                             */
/* ========================================================================================= */
/* ========================================================================== */
/*  系统控制                                                                   */
/* ========================================================================== */

/** @brief 获取上次复位原因
 *  @return 1=看门狗复位, 0=其他复位 */
uint8_t sysRstReason_get(void);

/** @brief 系统软复位 */
void system_reboot(void);

/** @brief 系统升级入口
 *  @param updateFlag 升级标志 */
void system_update_start(uint32_t updateFlag);

/* ========================================================================== */
/*  SCC3000 (ESC 传感器) 桩函数 — 已废弃                                        */
/*  SCC3000/IMU 驱动不在本工程范围, 数据由外部模块负责, 此处仅满足链接。          */
/* ========================================================================== */

/** @brief ESC 标定请求 (桩) */
void SCC3000_calibration_req(void);

/** @brief ESC 反标定请求 (桩) */
void SCC3000_UnCalibration_req(void);

/** @brief ESC 标定结果反馈 (桩: 恒返回 0=无标定流程)
 *  @return 0=无标定流程, 1=标定中, 2=成功, 3=失败 */
uint8_t SCC3000_calibration_resp(void);

/** @brief 获取 ESC 是否故障 (桩: 恒返回 0=无故障)
 * 
 *  @return 0=无故障, 1=有故障 */
uint8_t SCC3000_Err(void);

/* ========================================================================== */
/*  ECU 类型 (桩)                                                               */
/* ========================================================================== */

/** @brief 获取 ECU 类型 (桩)
 *  @return 0=驾驶室版, 1=底盘版 */
uint8_t get_ECU_type(void);

/* ========================================================================== */
/*  延时                                                                       */
/* ========================================================================== */

/**
 * @brief us 级延时 (基于 SysTick)
 * @param n 延时微秒数
 */
void delay_us(uint32_t n);

/* ========================================================================== */
/*  CAN 接口 (高层封装)                                                        */
/*                                                                            */
/*  CAN 驱动实现见 can.c/can.h, 对外接口见 RTE.h。              */
/* ========================================================================== */

/**
 * @brief 配置 CAN 收发 ID 列表 
 * @param canX         0=底盘CAN(CAN0), 1=调试CAN(CAN1)
 * @param canIDList    CAN ID 数组 (标准帧 ≤0x7FF, 扩展帧 >0x7FF)
 * @param idCount      ID 数量
 * @param transDirect  0=接收列表(配置过滤器), 1=发送列表(CAN0 发送白名单, CAN1 忽略)
 */
void can_info_cfg(uint8_t canX, uint32_t* canIDList, uint8_t idCount, uint8_t transDirect);

/**
 * @brief 初始化底盘CAN和调试CAN
 * @note  调用前需先 can_info_cfg 配置 ID, can0_bitrate_set 设置波特率
 */
void can_init(void);

#endif
