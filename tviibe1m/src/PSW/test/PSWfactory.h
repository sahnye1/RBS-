/**
 * @file    PSWfactory.h
 * @brief   工厂模式动作框架 — 声明 (实现见 PSWfactory.c)
 *
 * @note    每 10ms 调用一次 (cmn.c 的 PSW_10ms_deal ⑧.7 步, 紧跟 PSWoem 之后):
 *          模式判定: RTEfTestMode == PSWFACTORY_MODE(1) 时框架生效。
 *          命令通道与 OEM 模式共用 (访问接口 PSWmode_*, 实现见 PSWoem.c 第 3 节):
 *            RTEfDbgMsgSW  = 命令字 (执行后置 0xFF)
 *            RTEfDbgMsgSW1 = 参数1
 *            RTEfDbgMsgSW2 = 参数2
 *          两个模式互斥 (RTEfTestMode 同一时刻只能是一个值), 不会互相抢命令。
 *
 * @note    与 OEM 模式的唯一差别: 工厂模式不做任何电磁阀动作 —
 *          不调用 Bts724g_SetValve / Bts724g_NotifyValveActive,
 *          命令表里也不允许出现阀动作处理函数。
 *          命令表见 PSWfactory.c 的 s_factory_cmd_list[],
 *          新增命令 = 加一条表项 + 一个处理函数 (本文件加命令字宏)。
 *
 * @note    工厂模式属产品功能 (发布版保留), 非工厂模式下立即返回, 无运行开销。
 */
#ifndef PSWFACTORY_H
#define PSWFACTORY_H

/* ========================================================================== */
/*  模式值 (与 RTEfTestMode 的取值定义一致, 见 RTE.h 注释)                      */
/* ========================================================================== */
#define PSWFACTORY_MODE_NORMAL      0u    /* 正常模式 — 框架不动作                  */
#define PSWFACTORY_MODE_FACTORY     1u    /* 工厂测试模式 — 接收命令, 不打阀        */

/* ========================================================================== */
/*  命令字 (RTEfDbgMsgSW 的取值)                                                */
/*                                                                            */
/*  从 0x80 起分配: 与 OEM 模式的 0x00~0x02 分开, 即使误把 OEM 命令字下发到       */
/*  工厂模式, 也只会落空 (被消费掉), 不会误打阀。                                 */
/* ========================================================================== */
#define PSWFACTORY_CMD_NONE         0xFFu /* 空闲/无命令 (执行完由框架置回)         */
#define PSWFACTORY_CMD_NOP          0x80u /* 空动作 — 验证命令通道是否通, 参数回存  */

/* 后续命令预留 (待定, 只做非阀动作):
 *   0x81 读硬件状态 (电源/压力/轮速原始值) → 结果回读通道待通讯层确认
 *   0x82 读 EEPROM 参数
 *   0x83 写 EEPROM 参数 / 恢复默认
 *   0x84 继电器、低边输出等非阀输出自检
 */

/* ========================================================================== */
/*  对外接口                                                                    */
/* ========================================================================== */

/** @brief 工厂模式动作框架入口 (每 10ms 调用一次, 不含任何阀动作) */
void PSWfactory(void);

#endif /* PSWFACTORY_H */
